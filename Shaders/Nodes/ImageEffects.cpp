// Effects on a texture: blurs, edges, and the looks of lenses and screens (graphics_metal's
// Nodes/ImageEffects.swift). Each reads a bounded handful of samples around the pixel.
#include "NodeFamilies.h"

namespace editor::shaders {

using namespace spec;
using enum SocketType;

NodeGroup imageEffectNodes() {
    NodeBuilder c(NodeCategory::imageEffects);
    return {c.category, {
        c.node({.name = "blur", .label = "Blur", .summary = "Softens a texture: box, Gaussian, radial (degrees) or zoom (percent).",
                .symbol = "aqi.medium",
                .inputs = {tex(), vec2("uv", "UV"), num("radius", "Radius", 6, between(0, 30)),
                           vec2("center", "Center", Fallback::middle())},
                .outputs = {out("color", "Color", color, "blurImage({texture}, {uv}, {radius}, {#mode}, {center})")},
                .options = {option("mode", "Type", {"Box", "Gaussian", "Radial", "Zoom"}, 1)}}),
        c.simple("sharpen", "Sharpen", "Exaggerates a texture's edges.",
                 {tex(), vec2("uv", "UV"), num("amount", "Amount", 1, between(0, 5))}, color,
                 "sharpenImage({texture}, {uv}, {amount})", {.symbol = "triangle", .output = {"color", "Color"}}),
        c.node({.name = "edge-detect", .label = "Edge Detect", .summary = "Sobel edges of a texture's brightness.",
                .symbol = "square.dashed",
                .inputs = {tex(), vec2("uv", "UV"), num("strength", "Strength", 2, between(0, 10))},
                .outputs = {out("color", "Color", color, "float4(float3(edgeStrength({texture}, {uv}, {strength})), 1.0f)"),
                            out("edge", "Edge", number, "edgeStrength({texture}, {uv}, {strength})")}}),
        c.simple("emboss", "Emboss", "A texture's brightness as relief lit from an angle.",
                 {tex(), vec2("uv", "UV"), num("amount", "Amount", 2, between(0, 10)), num("angle", "Angle", 45, between(0, 360))}, color,
                 "embossImage({texture}, {uv}, {amount}, {angle})", {.symbol = "mountain.2", .output = {"color", "Color"}}),
        c.simple("chromatic-aberration", "Chromatic Aberration", "Splits red and blue apart toward the edges.",
                 {tex(), vec2("uv", "UV"), num("amount", "Amount", 1, between(0, 5)), vec2("center", "Center", Fallback::middle())}, color,
                 "chromaticAberration({texture}, {uv}, {amount}, {center})",
                 {.symbol = "circle.hexagongrid", .output = {"color", "Color"}}),
        c.simple("vignette", "Vignette", "Darkens a colour toward the edges.",
                 {col("color", "Color", Fallback::white()), vec2("position", "Position", Fallback::centred()),
                  num("radius", "Radius", 0.7, between(0, 2)), num("softness", "Softness", 0.5, between(0, 2)),
                  num("intensity", "Intensity", 0.8, between(0, 1))}, color,
                 "vignetteColor({color}, {position}, {radius}, {softness}, {intensity})",
                 {.symbol = "circle.dashed", .output = {"color", "Color"}}),
        c.simple("film-grain", "Film Grain", "Adds noise that changes 24 times a second.",
                 {col("color", "Color", Fallback::gray()), timeIn(), num("amount", "Amount", 0.2, between(0, 1)),
                  num("size", "Size", 1, between(1, 8))}, color,
                 "filmGrain({color}, fragCoord, {time}, {amount}, {size})",
                 {.symbol = "film.stack", .output = {"color", "Color"}}),
        c.simple("scanlines", "Scanlines", "A CRT: scanlines, a curved screen, an RGB mask and dark corners.",
                 {tex(), vec2("uv", "UV"), num("spacing", "Spacing", 3, between(1, 12)),
                  num("intensity", "Intensity", 0.6, between(0, 1)), num("curvature", "Curvature", 1, between(0, 4))}, color,
                 "scanlinesCrt({texture}, {uv}, fragCoord, {spacing}, {intensity}, {curvature})",
                 {.symbol = "tv", .output = {"color", "Color"}}),
        c.simple("bloom", "Bloom", "Makes what is brighter than a cutoff glow.",
                 {tex(), vec2("uv", "UV"), num("cutoff", "Cutoff", 0.6, between(0, 1)), num("radius", "Radius", 16, between(1, 60)),
                  num("intensity", "Intensity", 1, between(0, 4))}, color,
                 "bloomImage({texture}, {uv}, {cutoff}, {radius}, {intensity})",
                 {.symbol = "sun.max.fill", .output = {"color", "Color"}}),
        c.simple("pixelate", "Pixelate", "Blocks of one colour, a number of pixels wide.",
                 {tex(), vec2("uv", "UV"), num("size", "Size", 8, between(1, 64))}, color,
                 "pixelateImage({texture}, {uv}, {size})", {.symbol = "squareshape.split.3x3", .output = {"color", "Color"}}),
        c.simple("mosaic", "Mosaic", "Square tiles of one colour with grout between.",
                 {tex(), vec2("uv", "UV"), num("tiles", "Tiles", 12, between(2, 64)), num("gap", "Gap", 0.05, between(0, 0.4)),
                  num("variation", "Variation", 0.2, between(0, 1))}, color,
                 "mosaicImage({texture}, {uv}, float2(u.resolution.x / u.resolution.y, 1.0f), {tiles}, {gap}, {variation})",
                 {.symbol = "square.grid.3x3.fill", .output = {"color", "Color"}}),
        c.simple("displacement-map", "Displacement Map", "Moves a texture's pixels by another texture.",
                 {tex(), tex("map", "Map"), vec2("uv", "UV"), num("amount", "Amount", 0.1, between(-1, 1))}, color,
                 "displaceImage({texture}, {map}, {uv}, {amount}, {#source})",
                 {.symbol = "arrow.up.and.down.and.arrow.left.and.right",
                  .options = {option("source", "Map Reads", {"Red and Green", "Brightness Slope"}, 1)},
                  .output = {"color", "Color"}}),
        c.node({.name = "normal-from-height", .label = "Normal From Height",
                .summary = "A height texture's surface normal, or its relief lit from an angle.", .symbol = "rectangle.3.group",
                .inputs = {tex(), vec2("uv", "UV"), num("strength", "Strength", 4, between(0, 20)),
                           num("angle", "Light Angle", 45, between(0, 360))},
                .outputs = {out("color", "Color", color, "normalFromHeight({texture}, {uv}, {strength}, {#look}, {angle})")},
                .options = {option("look", "Look", {"Normal Map", "Bevel"})}}),
        c.simple("heat-haze", "Heat Haze", "Wobbles a texture like air over a flame.",
                 {tex(), vec2("uv", "UV"), timeIn(), num("strength", "Strength", 1.5, between(0, 10)),
                  num("scale", "Scale", 8, between(1, 40))}, color,
                 "imageTap({texture}, hazeUv({uv}, {strength}, {scale}, {time}))",
                 {.symbol = "wind", .output = {"color", "Color"}}),
        c.simple("lens-distortion", "Lens Distortion", "Barrel (positive) or pincushion (negative) distortion.",
                 {tex(), vec2("uv", "UV"), num("strength", "Strength", 0.3, between(-1, 1)), num("zoom", "Zoom", 1, between(0.5, 2))}, color,
                 "lensImage({texture}, {uv}, {strength}, {zoom})", {.symbol = "camera.aperture", .output = {"color", "Color"}}),
        c.simple("kuwahara", "Kuwahara", "A painterly smoothing that keeps edges.",
                 {tex(), vec2("uv", "UV"), num("radius", "Radius", 3, between(1, 4))}, color,
                 "kuwahara({texture}, {uv}, {radius})", {.symbol = "paintbrush.pointed", .output = {"color", "Color"}}),
    }};
}

} // namespace editor::shaders
