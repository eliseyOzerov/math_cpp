NodeGroup blendingNodes() {
    NodeBuilder c(NodeCategory::blending);
    return {c.category, {
        c.node({.name = "blend", .label = "Blend", .summary = "Lays one colour over another through a blend mode.",
                .symbol = "square.on.square",
                .inputs = {col("base", "Base", Fallback::gray()),
                           col("blend", "Blend", Fallback{"float4(0.9f, 0.4f, 0.2f, 1.0f)", "orange", std::nullopt}),
                           num("opacity", "Opacity", 1, between(0, 1))},
                .outputs = {out("color", "Color", color, "compositedWithBlend({base}, {blend}, {#mode}, {opacity})")},
                .options = {option("mode", "Mode",
                                   {"Normal", "Multiply", "Screen", "Overlay", "Soft Light", "Hard Light", "Add", "Subtract",
                                    "Difference", "Exclusion", "Color Dodge", "Color Burn", "Darken", "Lighten", "Hue",
                                    "Saturation", "Color", "Luminosity"})}}),
        c.simple("mask-blend", "Mask Blend", "Shows A where the mask is 0 and B where it is 1.",
                 {col("a", "A", Fallback::black()), col("b", "B", Fallback::white()), num("mask", "Mask", 0.5, between(0, 1))}, color,
                 "mix({a}, {b}, clamp({mask}, 0.0f, 1.0f))", {.symbol = "circle.lefthalf.filled", .output = {"color", "Color"}}),
        c.simple("alpha-over", "Alpha Over", "Composites a colour over another by its alpha.",
                 {col("background", "Background", Fallback::gray()),
                  col("foreground", "Foreground", Fallback{"float4(1.0f, 0.5f, 0.2f, 0.6f)", "translucent orange", std::nullopt})},
                 color, "straightAlphaOver({background}, {foreground})",
                 {.symbol = "square.2.layers.3d", .output = {"color", "Color"}}),
    }};
}

