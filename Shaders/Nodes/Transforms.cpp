// Reshaping coordinates before a pattern reads them: moving, turning, tiling and folding
// (graphics_metal's Nodes/Transforms.swift). Helper names are the kernels' (Kernels/ShaderCoordinates.h).
#include "NodeFamilies.h"

namespace editor::shaders {

using namespace spec;
using enum SocketType;

NodeGroup transformNodes() {
    NodeBuilder c(NodeCategory::transforms);
    const std::string aspect = "float2(u.resolution.x / max(u.resolution.y, 1.0f), 1.0f)";
    return {c.category, {
        c.node({.name = "uv", .label = "UV", .summary = "Coordinates across the canvas, 0 to 1 from the bottom left.",
                .symbol = "square.grid.2x2", .outputs = {out("uv", "UV", vector2, "vUv")}}),
        c.node({.name = "pixel-position", .label = "Pixel Position", .summary = "This pixel's position in pixels from the bottom left.",
                .symbol = "scope", .outputs = {out("position", "Position", vector2, "fragCoord")}}),
        c.node({.name = "canvas-size", .label = "Canvas Size", .summary = "The canvas's width and height in pixels.",
                .symbol = "aspectratio", .outputs = {out("size", "Size", vector2, "u.resolution")}}),
        c.node({.name = "pixel-size", .label = "Pixel Size", .summary = "One pixel's size in UV.", .symbol = "square.grid.4x3.fill",
                .outputs = {out("size", "Size", vector2, "(float2(1.0f) / max(u.resolution, float2(1.0f)))")}}),
        c.simple("center-coordinates", "Center Coordinates", "UV with the origin at the centre and square units.",
                 {vec2("coordinates", "Coordinates")}, vector2, "({coordinates} - 0.5f) * " + aspect,
                 {.symbol = "plus.viewfinder", .output = {"coordinates", "Coordinates"}}),
        c.simple("aspect-correct", "Aspect Correct", "UV stretched so its units are square, still centred on 0.5.",
                 {vec2("coordinates", "Coordinates")}, vector2, "({coordinates} - 0.5f) * " + aspect + " + 0.5f",
                 {.symbol = "arrow.left.and.right.square"}),
        c.simple("rotate-2d", "Rotate", "Turns coordinates around a centre, in degrees.",
                 {vec2("coordinates", "Coordinates"), num("angle", "Angle", 45, between(-360, 360)),
                  vec2("center", "Centre", Fallback::middle())}, vector2,
                 "rotatedCounterClockwise({coordinates} - {center}, degreesToRadians({angle})) + {center}",
                 {.symbol = "rotate.right"}),
        c.simple("scale-uv", "Scale", "Scales coordinates around a centre; more than 1 repeats a pattern more.",
                 {vec2("coordinates", "Coordinates"), num("scale", "Scale", 2, between(0, 10)), num("x", "X", 1, between(0, 10)),
                  num("y", "Y", 1, between(0, 10)), vec2("center", "Centre", Fallback::middle())}, vector2,
                 "({coordinates} - {center}) * float2({x}, {y}) * {scale} + {center}",
                 {.symbol = "arrow.up.left.and.arrow.down.right"}),
        c.simple("translate-uv", "Translate", "Moves coordinates.",
                 {vec2("coordinates", "Coordinates"), num("x", "X", 0.1, between(-1, 1)), num("y", "Y", 0, between(-1, 1))},
                 vector2, "{coordinates} + float2({x}, {y})", {.symbol = "arrow.up.and.down.and.arrow.left.and.right"}),
        c.node({.name = "tile", .label = "Tile",
                .summary = "Repeats coordinates in a grid: the position within each cell and the cell's index.",
                .symbol = "square.grid.3x3",
                .inputs = {vec2("coordinates", "Coordinates"), num("columns", "Columns", 4, between(1, 32)),
                           num("rows", "Rows", 4, between(1, 32))},
                .outputs = {out("coordinates", "Coordinates", vector2, "fract({$})"), out("cell", "Cell", vector2, "floor({$})"),
                            out("random", "Random", number, "hash21(floor({$}))")},
                .setup = "{coordinates} * float2({columns}, {rows})"}),
        c.node({.name = "polar-coordinates", .label = "Polar Coordinates",
                .summary = "A point's angle (radians) and distance from the origin.", .symbol = "circle.circle",
                .inputs = {vec2("coordinates", "Coordinates", Fallback::centred())},
                .outputs = {out("angle", "Angle", number, "atan2({coordinates}.y, {coordinates}.x)"),
                            out("radius", "Radius", number, "length({coordinates})"),
                            out("polar", "Polar UV", vector2,
                                "float2(atan2({coordinates}.y, {coordinates}.x) / tau<float>() + 0.5f, length({coordinates}))")}}),
        c.simple("cartesian-coordinates", "Cartesian Coordinates", "A point from an angle (radians) and a radius.",
                 {num("angle", "Angle", 0, between(-6.2832, 6.2832)), num("radius", "Radius", 0.5)}, vector2,
                 "float2(cos({angle}), sin({angle})) * {radius}", {.symbol = "plus.square"}),
        c.simple("mirror", "Mirror", "Folds coordinates across an axis through the origin.",
                 {vec2("coordinates", "Coordinates", Fallback::centred())}, vector2, "mirroredUv({coordinates}, {#axis})",
                 {.symbol = "arrow.left.and.right.righttriangle.left.righttriangle.right",
                  .options = {option("axis", "Axis", {"X", "Y", "Both"}, 2)}}),
        c.simple("kaleidoscope", "Kaleidoscope", "Folds coordinates into mirrored wedges around the origin.",
                 {vec2("coordinates", "Coordinates", Fallback::centred()), num("segments", "Segments", 6, between(1, 24)),
                  num("angle", "Angle", 0, between(-360, 360))}, vector2,
                 "kaleidoscopeFolded({coordinates}, {segments}, degreesToRadians({angle}))", {.symbol = "asterisk.circle"}),
        c.simple("twirl", "Twirl", "Twists coordinates around the origin, most at the centre.",
                 {vec2("coordinates", "Coordinates", Fallback::centred()), num("strength", "Strength", 3, between(-12, 12)),
                  num("radius", "Radius", 0.5, between(0, 2))}, vector2, "twirled({coordinates}, {strength}, {radius})",
                 {.symbol = "tornado"}),
        c.simple("spherize", "Spherize", "Bulges (positive) or pinches (negative) a disc around the origin.",
                 {vec2("coordinates", "Coordinates", Fallback::centred()), num("strength", "Strength", 0.6, between(-0.9, 3)),
                  num("radius", "Radius", 0.45, between(0, 2))}, vector2, "spherized({coordinates}, {strength}, {radius})",
                 {.symbol = "globe"}),
        c.simple("flip", "Flip", "Flips UV horizontally, vertically or both.", {vec2("coordinates", "Coordinates")}, vector2,
                 "flippedUv({coordinates}, {#axis})",
                 {.symbol = "arrow.up.and.down.righttriangle.up.righttriangle.down",
                  .options = {option("axis", "Axis", {"X", "Y", "Both"})}}),
        c.node({.name = "offset-rows", .label = "Offset Rows", .summary = "A grid with every other row (or column) slid along, for bricks.",
                .symbol = "line.3.horizontal.decrease",
                .inputs = {vec2("coordinates", "Coordinates"), num("columns", "Columns", 4, between(1, 32)),
                           num("rows", "Rows", 8, between(1, 32)), num("offset", "Offset", 0.5, between(0, 1))},
                .outputs = {out("coordinates", "Coordinates", vector2, "fract({$})"), out("cell", "Cell", vector2, "floor({$})")},
                .options = {option("direction", "Offset", {"Rows", "Columns"})},
                .setup = "rowOffsetGrid({coordinates}, float2({columns}, {rows}), {offset}, {#direction})"}),
        c.node({.name = "hex-grid", .label = "Hex Grid",
                .summary = "Hexagonal cells: the position in each, its centre, edge distance and a random id.", .symbol = "hexagon",
                .inputs = {vec2("coordinates", "Coordinates", Fallback::centred()), num("scale", "Scale", 6, between(0.5, 40))},
                .outputs = {out("local", "Local", vector2, "{$}.xy"), out("cell", "Cell", vector2, "{$}.zw"),
                            out("edge", "Edge", number, "hexagonalEdgeDistance({$}.xy)"),
                            out("random", "Random", number, "hash21({$}.zw * 2.0f + 0.5f)")},
                .setup = "hexagonalGrid({coordinates} * {scale})"}),
        c.node({.name = "triangle-grid", .label = "Triangle Grid",
                .summary = "Equilateral triangle cells: position, edge distance and a random id.", .symbol = "triangle",
                .inputs = {vec2("coordinates", "Coordinates", Fallback::centred()), num("scale", "Scale", 6, between(0.5, 40))},
                .outputs = {out("local", "Local", vector2, "{$}.xy"), out("edge", "Edge", number, "{$}.z"),
                            out("random", "Random", number, "{$}.w")},
                .setup = "triangularGrid({coordinates} * {scale})"}),
        c.simple("domain-warp", "Domain Warp", "Pushes coordinates along a vector field, such as noise.",
                 {vec2("coordinates", "Coordinates"), vec2("offset", "Offset", Fallback::zero()),
                  num("strength", "Strength", 0.1, between(-1, 1))}, vector2,
                 "{coordinates} + ({offset} - 0.5f) * 2.0f * {strength}", {.symbol = "scribble"}),
        c.simple("pixelate-uv", "Pixelate UV", "Snaps coordinates to the centres of square cells.",
                 {vec2("coordinates", "Coordinates"), num("cells", "Cells", 32, between(1, 512))}, vector2,
                 "pixelatedUv({coordinates}, {cells}, u.resolution.x / max(u.resolution.y, 1.0f))",
                 {.symbol = "square.grid.3x3.fill"}),
        c.simple("matrix-2x2", "Matrix 2×2", "Multiplies coordinates by a 2×2 matrix, given by rows.",
                 {vec2("coordinates", "Coordinates", Fallback::centred()), num("m11", "Row 1, 1", 1), num("m12", "Row 1, 2", 0),
                  num("m21", "Row 2, 1", 0), num("m22", "Row 2, 2", 1)}, vector2,
                 "float2x2(float2({m11}, {m21}), float2({m12}, {m22})) * {coordinates}"),
        c.simple("matrix-3x3", "Matrix 3×3", "Transforms coordinates by a 3×3 matrix, given by rows, with perspective.",
                 {vec2("coordinates", "Coordinates", Fallback::centred()),
                  num("m11", "Row 1, 1", 1), num("m12", "Row 1, 2", 0), num("m13", "Row 1, 3", 0),
                  num("m21", "Row 2, 1", 0), num("m22", "Row 2, 2", 1), num("m23", "Row 2, 3", 0),
                  num("m31", "Row 3, 1", 0), num("m32", "Row 3, 2", 0), num("m33", "Row 3, 3", 1)}, vector2,
                 "transformedByMatrix3({coordinates}, float3({m11}, {m21}, {m31}), float3({m12}, {m22}, {m32}), float3({m13}, {m23}, {m33}))"),
    }};
}

} // namespace editor::shaders
