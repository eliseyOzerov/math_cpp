NodeGroup waveNodes() {
    NodeBuilder c(NodeCategory::waves);
    const std::vector<std::string> shapes = {"Sine", "Triangle", "Square", "Sawtooth"};
    return {c.category, {
        c.simple("wave", "Wave", "A repeating wave from −1 to 1: sine, triangle, square or sawtooth.",
                 {anyIn("x", "X"), num("frequency", "Frequency", 1), num("amplitude", "Amplitude", 1), num("phase", "Phase")},
                 any, "waveShape({x} * {frequency} + {phase}, {#shape}) * {amplitude}",
                 {.symbol = "waveform", .options = {option("shape", "Shape", shapes)}}),
        c.simple("pulse", "Pulse", "1 for the duty part of each cycle, else 0.",
                 {anyIn("x", "X"), num("frequency", "Frequency", 1), num("duty", "Duty", 0.5, between(0, 1))}, any,
                 "step(fract({x} * {frequency}), {T}({duty}))", {.symbol = "waveform.path.ecg"}),
        c.simple("oscillator", "Oscillator", "A wave over time.",
                 {timeIn(), num("frequency", "Frequency", 0.5), num("amplitude", "Amplitude", 1), num("phase", "Phase"),
                  num("offset", "Offset")}, number,
                 "waveShape({time} * {frequency} + {phase}, {#shape}) * {amplitude} + {offset}",
                 {.symbol = "waveform.path", .options = {option("shape", "Shape", shapes)}}),
        c.simple("bounce", "Bounce", "A bouncing ball's height over time, from 0 to the height.",
                 {timeIn(), num("speed", "Speed", 1), num("height", "Height", 1)}, number,
                 "{height} * 4.0f * fract({time} * {speed}) * (1.0f - fract({time} * {speed}))",
                 {.symbol = "arrow.down.and.line.horizontal.and.arrow.up"}),
        c.simple("spring", "Spring", "A damped oscillation that settles, restarting each period.",
                 {timeIn(), num("frequency", "Frequency", 2), num("damping", "Damping", 3, between(0, 20)), num("period", "Period", 3)},
                 number,
                 "exp(-{damping} * flooredModulo({time}, max({period}, 0.000001f))) * cos(tau<float>() * {frequency} * flooredModulo({time}, max({period}, 0.000001f)))",
                 {.symbol = "arrow.up.and.down.circle"}),
    }};
}

